"""The definition data written as `definition.generated.ts`: one exported constant, `as const`.

Layout: an object or array holding only plain values (strings, numbers, booleans, lists of them) is
written on one line; anything else is expanded, one entry per line. The dialectes' formatter keeps an
object expanded when its source opens it on a new line, so this rule decides the formatted layout too.
"""
import math
import re
from typing import Any

HEADER = '// Auto-generated by @dialecte/create - do not edit'

IDENTIFIER = re.compile(r'^[A-Za-z_$][A-Za-z0-9_$]*$')


def definition_source(data: dict[str, Any]) -> str:
    """The TypeScript source of `definition.generated.ts` for the definition data `data`."""
    return f'{HEADER}\n\nexport const DEFINITION = {_value(data, depth=0)} as const\n'


def _value(value: Any, *, depth: int) -> str:
    if isinstance(value, dict):
        return _object(value, depth=depth)
    if isinstance(value, list):
        return _array(value, depth=depth)
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, int):
        return repr(value)
    if isinstance(value, float):
        if not math.isfinite(value):
            raise ValueError(f'TypeScript has no literal for {value!r}: write it as a lexical string')
        return repr(value)
    if isinstance(value, str):
        return _string(value)
    raise TypeError(f'a definition holds no {type(value).__name__}: {value!r}')


def _object(value: dict[str, Any], *, depth: int) -> str:
    if not value:
        return '{}'
    entries = [f'{_key(key)}: {_value(item, depth=depth + 1)}' for key, item in value.items()]
    if all(_is_plain(item) for item in value.values()):
        return '{ ' + ', '.join(entries) + ' }'
    indent = '\t' * (depth + 1)
    return '{\n' + ''.join(f'{indent}{entry},\n' for entry in entries) + '\t' * depth + '}'


def _array(value: list[Any], *, depth: int) -> str:
    if all(_is_scalar(item) for item in value):
        return '[' + ', '.join(_value(item, depth=depth) for item in value) + ']'
    indent = '\t' * (depth + 1)
    return '[\n' + ''.join(f'{indent}{_value(item, depth=depth + 1)},\n' for item in value) + '\t' * depth + ']'


def _is_scalar(value: Any) -> bool:
    return isinstance(value, str | bool | int | float)


def _is_plain(value: Any) -> bool:
    """A scalar, or a list of scalars."""
    return _is_scalar(value) or (isinstance(value, list) and all(_is_scalar(item) for item in value))


def _key(name: str) -> str:
    return name if IDENTIFIER.match(name) else _string(name)


def _string(text: str) -> str:
    escaped = text.replace('\\', '\\\\').replace("'", "\\'").replace('\n', '\\n').replace('\r', '\\r').replace('\t', '\\t')
    return f"'{escaped}'"
