"""The definition written as TypeScript reads back as the very data the generator built."""
import json
import shutil
import subprocess
from pathlib import Path

import pytest

from generate_next.emit.ts_literal import definition_source

DATA = {
    'Root': {
        'tag': 'Root',
        'namespace': {'prefix': '', 'uri': 'urn:dialecte:test'},
        'documentation': "It's the root.\nSecond line\twith a tab \\ and a backslash.",
        'parents': [],
        'attributes': {
            'sequence': ['e:version', 'name'],
            'any': True,
            'anyNamespace': ['##other'],
            'details': {
                'e:version': {'namespace': {'prefix': 'e', 'uri': 'urn:dialecte:ext'}, 'type': {'builtin': 'token'}},
                'name': {'required': True, 'type': {'builtin': 'Name'}},
            },
        },
        'children': {'sequence': ['boolean-value'], 'details': {'boolean-value': {}}},
    },
    'boolean-value': {
        'tag': 'boolean-value',
        'namespace': {'prefix': '', 'uri': 'urn:dialecte:test'},
        'parents': ['Root'],
        'attributes': {'sequence': [], 'details': {}},
        'children': {'sequence': [], 'details': {}},
    },
}


@pytest.mark.skipif(shutil.which('node') is None, reason='needs Node to read the emitted file back')
def test_the_emitted_definition_reads_back_as_the_data_it_was_built_from(tmp_path: Path) -> None:
    emitted = tmp_path / 'definition.generated.ts'
    emitted.write_text(definition_source(DATA), encoding='utf-8')
    script = f"const m = await import({json.dumps(emitted.as_uri())}); process.stdout.write(JSON.stringify(m.DEFINITION))"
    run = subprocess.run(['node', '--input-type=module', '-e', script], capture_output=True, text=True, check=True)
    assert json.loads(run.stdout) == DATA


def test_a_number_typescript_cannot_write_is_refused() -> None:
    with pytest.raises(ValueError, match='inf'):
        definition_source({'Root': {'limit': float('inf')}})


def test_the_layout_writes_plain_objects_on_one_line_and_expands_the_rest() -> None:
    source = definition_source(
        {
            'Root': {
                'namespace': {'prefix': '', 'uri': 'urn:t'},
                'parents': [],
                'attributes': {'sequence': ['a'], 'details': {'a': {'required': True, 'default': 'x\ry'}}},
                'contentModel': [{'kind': 'element', 'name': 'A'}],
            }
        }
    )
    assert source == (
        '// Auto-generated by @dialecte/create - do not edit\n'
        '\n'
        'export const DEFINITION = {\n'
        '\tRoot: {\n'
        "\t\tnamespace: { prefix: '', uri: 'urn:t' },\n"
        '\t\tparents: [],\n'
        '\t\tattributes: {\n'
        "\t\t\tsequence: ['a'],\n"
        '\t\t\tdetails: {\n'
        "\t\t\t\ta: { required: true, default: 'x\\ry' },\n"
        '\t\t\t},\n'
        '\t\t},\n'
        '\t\tcontentModel: [\n'
        "\t\t\t{ kind: 'element', name: 'A' },\n"
        '\t\t],\n'
        '\t},\n'
        '} as const\n'
    )


def test_the_emitted_definition_is_one_exported_constant_as_const() -> None:
    source = definition_source(DATA)
    assert source.startswith('// Auto-generated by @dialecte/create - do not edit\n\nexport const DEFINITION = {\n')
    assert source.endswith('\n} as const\n')


@pytest.mark.skipif(shutil.which('node') is None, reason='needs Node to read the emitted file back')
def test_a_generated_definition_with_content_models_reads_back_as_built(definition_of, tmp_path: Path) -> None:
    data = definition_of(
        '<xs:schema xmlns:xs="http://www.w3.org/2001/XMLSchema" xmlns="urn:t" targetNamespace="urn:t" elementFormDefault="qualified">'
        '<xs:element name="Root"><xs:complexType><xs:sequence>'
        '<xs:element name="A" minOccurs="0" maxOccurs="3"/><xs:choice><xs:sequence/><xs:any namespace="##other"/></xs:choice>'
        '<xs:element name="Count" type="xs:int" default="0"/></xs:sequence>'
        '<xs:attribute name="flag" type="xs:boolean"/><xs:anyAttribute namespace="##any"/></xs:complexType></xs:element></xs:schema>'
    )
    emitted = tmp_path / 'definition.generated.ts'
    emitted.write_text(definition_source(data), encoding='utf-8')
    script = f"const m = await import({json.dumps(emitted.as_uri())}); process.stdout.write(JSON.stringify(m.DEFINITION))"
    run = subprocess.run(['node', '--input-type=module', '-e', script], capture_output=True, text=True, check=True)
    assert json.loads(run.stdout) == data
