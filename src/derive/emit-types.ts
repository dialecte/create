import { attributesDeclaredUnder, elementChildren, findDeclaredEdges } from './declared-edges.ts'
import { deriveTypeNames, edgeTypeName, tsKey, tsString } from './ts-syntax.ts'
import { enumerated, typedAttributes } from './typed-attributes.ts'

import type { AttributeData, DeclaredEdge, DefinitionData, ElementData } from './derive.types.ts'

/**
 * `types.generated.ts`: one attribute type per element (and per declaration of a homonym), derived from the definition,
 * its values read from each attribute's datatype.
 */
export function emitTypesSource(params: { definition: DefinitionData }): string {
	const { definition } = params
	const names = Object.keys(definition).sort()
	const typeNames = deriveTypeNames(names)
	const lines = [
		'// Auto-generated by @dialecte/create - do not edit',
		'',
		"import type { ELEMENT_NAMES, REQUIRED_ATTRIBUTES } from './constants.generated'",
		'',
		'export type AvailableElement = (typeof ELEMENT_NAMES)[number]',
		'',
	]

	const edgesByChild = new Map<string, DeclaredEdge[]>()
	for (const edge of findDeclaredEdges({ definition })) {
		edgesByChild.set(edge.child, [...(edgesByChild.get(edge.child) ?? []), edge])
	}

	for (const name of names) {
		const element = definition[name]
		if (element === undefined) continue
		lines.push(
			...attributeType({
				typeName: `Attributes${typeNames.get(name)}`,
				attributes: typedAttributes(element),
			}),
		)
		// a homonym: one type per declaration, the way it reads under that parent
		const declarations = [...(edgesByChild.get(name) ?? [])].sort((first, second) =>
			first.parent < second.parent ? -1 : 1,
		)
		for (const { parent, attributes } of declarations) {
			lines.push(
				...attributeType({
					typeName: edgeTypeName({ typeNames, element: name, parent }),
					attributes,
				}),
			)
		}
	}

	lines.push('export type AttributesMap = {')
	for (const name of names) lines.push(`\t${tsKey(name)}: Attributes${typeNames.get(name)}`)
	lines.push('}', '', 'export type AttributesOf<T extends AvailableElement> = AttributesMap[T]', '')
	lines.push(
		'/**',
		' * The attributes of a child AS DECLARED UNDER each parent. An element declared once has the',
		' * same type under every parent; a homonym has the type of its declaration under each. Read',
		" * through the dialecte's `AttributesOf<Element, Parent>`; the constant `ATTRIBUTES.byParent`",
		' * is checked against this map.',
		' */',
		'export type AttributesByParent = {',
	)
	for (const parent of names) {
		const children = elementChildren({ definition, parent })
		if (children.length === 0) continue
		lines.push(`\t${tsKey(parent)}: {`)
		for (const child of children) {
			const declared = attributesDeclaredUnder({ definition, parent, child }) !== undefined
			const childType = declared
				? edgeTypeName({ typeNames, element: child, parent })
				: `Attributes${typeNames.get(child)}`
			lines.push(`\t\t${tsKey(child)}: ${childType}`)
		}
		lines.push('\t}')
	}
	lines.push(
		'}',
		'',
		'export type RequiredAttributeNames<T extends AvailableElement> =',
		'\t(typeof REQUIRED_ATTRIBUTES)[T][number]',
		'export type OptionalAttributeNames<T extends AvailableElement> = Exclude<',
		'\tkeyof AttributesOf<T>,',
		'\tRequiredAttributeNames<T>',
		'>',
		'',
	)
	return lines.join('\n')
}

function attributeType(params: {
	typeName: string
	attributes: ElementData['attributes']
}): string[] {
	const { typeName, attributes } = params
	const lines = [`export type ${typeName} = {`]
	for (const name of attributes.sequence) {
		const attribute = attributes.details[name] ?? {}
		const optional = attribute.required === true ? '' : '?'
		lines.push(`\t${tsKey(name)}${optional}: ${valueType({ attribute })}`)
	}
	lines.push('}', '')
	return lines
}

/** An enumeration becomes a union of its values (open to others), a fixed value its literal, the rest `string`. */
function valueType(params: { attribute: AttributeData }): string {
	const { attribute } = params
	const enumeration = enumerated(attribute.type)
	if (enumeration !== undefined && enumeration.length > 0) {
		return `${enumeration.map(tsString).join(' | ')} | (string & {})`
	}
	if (attribute.fixed !== undefined && attribute.fixed !== '') return tsString(attribute.fixed)
	return 'string'
}
