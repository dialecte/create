import { elementChildren, findDeclaredEdges, shapeDeclaredUnder } from './declared-edges.ts'
import { deriveTypeNames, edgeTypeName, tsKey, tsString } from './ts-syntax.ts'
import { enumerated } from './typed-attributes.ts'
import { XSI_TYPE, attributeShape, xsiTypeLiterals } from './xsi-type-shapes.ts'

import type {
	AttributeData,
	AttributeShape,
	DeclaredEdge,
	DefinitionData,
	ElementData,
	TypesData,
} from './derive.types.ts'

/**
 * `types.generated.ts`: one attribute type per element (and per declaration of a homonym), derived from the definition,
 * its values read from each attribute's datatype. An element that may name a type with `xsi:type` gets a union on
 * it: its own attributes, and one type per type it may name (`AttributesType_<type>`), each by the literal core
 * stores.
 */
export function emitTypesSource(params: {
	definition: DefinitionData
	types: TypesData
	root: string
}): string {
	const { definition, types, root } = params
	const literalOf = xsiTypeLiterals({ definition, root })
	const names = Object.keys(definition).sort()
	const typeNames = deriveTypeNames(names)
	// by element name, sorted
	const shapes = new Map(
		Object.entries(definition)
			.sort(([first], [second]) => (first < second ? -1 : 1))
			.map(([name, element]) => [name, attributeShape({ content: element, types, literalOf })]),
	)

	const edgesByChild = new Map<string, DeclaredEdge[]>()
	for (const edge of findDeclaredEdges({ definition, types, literalOf })) {
		edgesByChild.set(edge.child, [...(edgesByChild.get(edge.child) ?? []), edge])
	}

	// every type an element may name, once, by its literal: the tag level of an element names every type any of
	// its declarations may
	const variants = new Map(
		[...shapes.values()]
			.flatMap((shape) => shape.variants)
			.map((variant) => [variant.literal, variant] as const),
	)
	const variantNames = deriveTypeNames([...variants.keys()])
	const variantTypeName = (literal: string): string => `AttributesType_${variantNames.get(literal)}`

	const lines = [
		'// Auto-generated by @dialecte/create - do not edit',
		'',
		"import type { ELEMENT_NAMES, REQUIRED_ATTRIBUTES } from './constants.generated'",
		'',
		'export type AvailableElement = (typeof ELEMENT_NAMES)[number]',
		'',
	]

	for (const { literal, attributes } of [...variants.values()].sort((first, second) =>
		first.literal < second.literal ? -1 : 1,
	)) {
		lines.push(
			`export type ${variantTypeName(literal)} = {`,
			`\t${tsKey(XSI_TYPE)}: ${tsString(literal)}`,
			...attributeLines({ attributes, indent: '\t' }),
			'}',
			'',
		)
	}

	for (const [name, shape] of shapes) {
		lines.push(
			...shapeType({ typeName: `Attributes${typeNames.get(name)}`, shape, variantTypeName }),
		)
		// a homonym: one type per declaration, the way it reads under that parent
		const declarations = [...(edgesByChild.get(name) ?? [])].sort((first, second) =>
			first.parent < second.parent ? -1 : 1,
		)
		for (const { parent, shape: declared } of declarations) {
			lines.push(
				...shapeType({
					typeName: edgeTypeName({ typeNames, element: name, parent }),
					shape: declared,
					variantTypeName,
				}),
			)
		}
	}

	lines.push('export type AttributesMap = {')
	for (const name of names) lines.push(`\t${tsKey(name)}: Attributes${typeNames.get(name)}`)
	lines.push('}', '', 'export type AttributesOf<T extends AvailableElement> = AttributesMap[T]', '')
	lines.push(
		'/**',
		' * The attributes of a child AS DECLARED UNDER each parent. An element declared once has the',
		' * same type under every parent; a homonym has the type of its declaration under each. Read',
		" * through the dialecte's `AttributesOf<Element, Parent>`; the constant `ATTRIBUTES.byParent`",
		' * is checked against this map.',
		' */',
		'export type AttributesByParent = {',
	)
	for (const parent of names) {
		const children = elementChildren({ definition, parent })
		if (children.length === 0) continue
		lines.push(`\t${tsKey(parent)}: {`)
		for (const child of children) {
			const declared =
				shapeDeclaredUnder({ definition, types, literalOf, parent, child }) !== undefined
			const childType = declared
				? edgeTypeName({ typeNames, element: child, parent })
				: `Attributes${typeNames.get(child)}`
			lines.push(`\t\t${tsKey(child)}: ${childType}`)
		}
		lines.push('\t}')
	}
	lines.push(
		'}',
		'',
		'export type RequiredAttributeNames<T extends AvailableElement> =',
		'\t(typeof REQUIRED_ATTRIBUTES)[T][number]',
		'/** Every attribute name a member of the type offers, but the required ones. */',
		'export type OptionalAttributeNames<T extends AvailableElement> = Exclude<',
		'\tAttributesOf<T> extends infer Member ? (Member extends unknown ? keyof Member : never) : never,',
		'\tRequiredAttributeNames<T>',
		'>',
		'',
	)
	return lines.join('\n')
}

/**
 * An attribute type: its own attributes alone, or - where it may name a type with `xsi:type` - the union of its own
 * member (closed: `xsi:type` names its own type or is absent) and one per type it may name.
 */
function shapeType(params: {
	typeName: string
	shape: AttributeShape
	variantTypeName: (literal: string) => string
}): string[] {
	const { typeName, shape, variantTypeName } = params
	const named = shape.variants.map(({ literal }) => variantTypeName(literal))
	// no own member: an abstract type, which has variants
	if (shape.own === undefined) return [`export type ${typeName} = ${named.join(' | ')}`, '']
	if (named.length === 0) {
		const { attributes } = shape.own
		return [`export type ${typeName} = {`, ...attributeLines({ attributes, indent: '\t' }), '}', '']
	}
	const ownType =
		shape.own.literals.length === 0 ? 'never' : shape.own.literals.map(tsString).join(' | ')
	return [
		`export type ${typeName} =`,
		'\t| {',
		...attributeLines({ attributes: shape.own.attributes, indent: '\t\t\t' }),
		`\t\t\t${tsKey(XSI_TYPE)}?: ${ownType}`,
		'\t  }',
		...named.map((name) => `\t| ${name}`),
		'',
	]
}

function attributeLines(params: {
	attributes: ElementData['attributes']
	indent: string
}): string[] {
	const { attributes, indent } = params
	return attributes.sequence.map((name) => {
		const attribute = attributes.details[name] ?? {}
		const optional = attribute.required === true ? '' : '?'
		return `${indent}${tsKey(name)}${optional}: ${valueType({ attribute })}`
	})
}

/** An enumeration becomes a union of its values (open to others), a fixed value its literal, the rest `string`. */
function valueType(params: { attribute: AttributeData }): string {
	const { attribute } = params
	const enumeration = enumerated(attribute.type)
	if (enumeration.length > 0) {
		return `${enumeration.map(tsString).join(' | ')} | (string & {})`
	}
	if (attribute.fixed !== undefined && attribute.fixed !== '') return tsString(attribute.fixed)
	return 'string'
}
