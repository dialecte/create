import { elementChildren, findDeclaredEdges, shapeDeclaredUnder } from './declared-edges.ts'
import { deriveGraph } from './derive-graph.ts'
import { deriveSingletons } from './derive-singletons.ts'
import {
	deriveTypeNames,
	edgeTypeName,
	tsKey,
	tsMember,
	tsRecord,
	tsStringArray,
} from './ts-syntax.ts'
import { attributeShape, shapeKeys, xsiTypeLiterals } from './xsi-type-shapes.ts'

import type { AttributeShape, DefinitionData, LiteralOf, TypesData } from './derive.types.ts'

/** `constants.generated.ts`: the lookup tables a dialecte config is built from, derived from the definition. */
export function emitConstantsSource(params: {
	definition: DefinitionData
	root: string
	types: TypesData
}): string {
	const { definition, root, types } = params
	const names = Object.keys(definition).sort()
	const typeNames = deriveTypeNames(names)
	const graph = deriveGraph({ definition })
	const literalOf = xsiTypeLiterals({ definition, root })
	const edgeTypes = findDeclaredEdges({ definition, types, literalOf })
		.map(({ parent, child }) => edgeTypeName({ typeNames, element: child, parent }))
		.sort()
	const imports = ['AvailableElement', 'AttributesOf', 'AttributesByParent', ...edgeTypes].join(
		', ',
	)

	return [
		'// Auto-generated by @dialecte/create - do not edit',
		'',
		`import type { ${imports} } from './types.generated'`,
		'',
		`export const ELEMENT_NAMES = ${tsStringArray(names)} as const`,
		'',
		`export const CHILDREN = ${tsRecord(graph.children)} as const`,
		'',
		`export const PARENTS = ${tsRecord(graph.parents)} as const`,
		'',
		`export const DESCENDANTS = ${tsRecord(graph.descendants)} as const`,
		'',
		`export const ANCESTORS = ${tsRecord(graph.ancestors)} as const`,
		'',
		`export const ROOT_ELEMENT = '${root}' as const`,
		'',
		`export const SINGLETON_ELEMENTS = ${tsStringArray(deriveSingletons({ definition, root, types }))} as const`,
		'',
		`const ATTRIBUTES_BY_TAG = ${attributesByTag({ definition, types, literalOf })} as const`,
		'',
		'/**',
		' * Attribute skeletons: one key per attribute name, typed for the type system; what an attribute',
		' * is (required, fixed, facets) lives in `DEFINITION`. `byTag` is the shape of an element wherever',
		' * it appears; `byParent` its shape AS DECLARED UNDER each parent, the same object where the schema',
		' * declares the tag once, its own where a homonym differs.',
		' */',
		'export const ATTRIBUTES = {',
		'\tbyTag: ATTRIBUTES_BY_TAG,',
		`\tbyParent: ${attributesByParent({ definition, types, literalOf, names, typeNames })} satisfies AttributesByParent,`,
		'} as const',
		'',
		`export const REQUIRED_ATTRIBUTES = ${tsRecord(requiredAttributes({ definition }))} as const satisfies Record<AvailableElement, readonly string[]>`,
		'',
	].join('\n')
}

/** One skeleton per element: a key per attribute name any member of its type offers (`shapeKeys`). */
function attributesByTag(params: {
	definition: DefinitionData
	types: TypesData
	literalOf: LiteralOf
}): string {
	const { definition, types, literalOf } = params
	const lines = ['{']
	// by element name, sorted
	const elements = Object.entries(definition).sort(([first], [second]) => (first < second ? -1 : 1))
	for (const [name, element] of elements) {
		const shape = attributeShape({ content: element, types, literalOf })
		const sequence = shapeKeys({ shape })
		if (sequence.length === 0) {
			lines.push(`\t${tsKey(name)}: {} as AttributesOf<'${name}'>,`)
			continue
		}
		lines.push(`\t${tsKey(name)}: {`)
		for (const attribute of sequence) {
			lines.push(`\t\t${tsKey(attribute)}: ${skeletonValue(shape)},`)
		}
		lines.push(`\t} as AttributesOf<'${name}'>,`)
	}
	lines.push('}')
	return lines.join('\n')
}

/** One row per parent, one entry per child: the by-tag object, or its own skeleton where a homonym differs. */
function attributesByParent(params: {
	definition: DefinitionData
	types: TypesData
	literalOf: LiteralOf
	names: readonly string[]
	typeNames: ReadonlyMap<string, string>
}): string {
	const { definition, types, literalOf, names, typeNames } = params
	const lines = ['{']
	for (const parent of names) {
		const children = elementChildren({ definition, parent })
		if (children.length === 0) continue
		lines.push(`\t\t${tsKey(parent)}: {`)
		for (const child of children) {
			const declared = shapeDeclaredUnder({ definition, types, literalOf, parent, child })
			if (declared === undefined) {
				lines.push(`\t\t\t${tsKey(child)}: ATTRIBUTES_BY_TAG${tsMember(child)},`)
				continue
			}
			const typeName = edgeTypeName({ typeNames, element: child, parent })
			lines.push(`\t\t\t${tsKey(child)}: ${skeleton(declared)} as ${typeName},`)
		}
		lines.push('\t\t},')
	}
	lines.push('\t}')
	return lines.join('\n')
}

function skeleton(shape: AttributeShape): string {
	const sequence = shapeKeys({ shape })
	if (sequence.length === 0) return '{}'
	const value = skeletonValue(shape)
	return `{ ${sequence.map((attribute) => `${tsKey(attribute)}: ${value}`).join(', ')} }`
}

/**
 * The value of a skeleton key, typed so the skeleton casts to its attribute type: a member of a union has the keys of
 * the others as `?: undefined`, which a `string` would not overlap.
 */
function skeletonValue(shape: AttributeShape): string {
	return shape.variants.length === 0 ? "'' as string" : "'' as string | undefined"
}

function requiredAttributes(params: { definition: DefinitionData }): Record<string, string[]> {
	const { definition } = params
	return Object.fromEntries(
		Object.entries(definition).map(([name, element]) => [
			name,
			Object.entries(element.attributes.details)
				.filter(([, attribute]) => attribute.required === true)
				.map(([attribute]) => attribute)
				.sort(),
		]),
	)
}
